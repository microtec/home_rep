/* Ricalcolo totale vendita quando cambiano le righe */
CREATE TRIGGER TR_VENDITE_RIGHE_AIUD FOR VENDITE_RIGHE ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 0 AS
DECLARE VARIABLE VID INTEGER;
BEGIN
  IF (DELETING) THEN VID = OLD.ID_VENDITA; ELSE VID = NEW.ID_VENDITA;
  UPDATE VENDITE V SET
    V.IMPONIBILE = COALESCE((SELECT SUM(R.QUANTITA * R.PREZZO) FROM VENDITE_RIGHE R WHERE R.ID_VENDITA = :VID), 0),
    V.TOTALE = V.IMPONIBILE - V.SCONTO
  WHERE V.ID = :VID;
END^

