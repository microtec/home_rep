  ATTIVO      SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_OPERATORI PRIMARY KEY (ID)
);

CREATE TABLE SERVIZI (
  ID          INTEGER NOT NULL,
  DESCRIZIONE VARCHAR(80) NOT NULL,
  DURATA_MIN  INTEGER DEFAULT 30 NOT NULL,
  PREZZO      NUMERIC(10,2) DEFAULT 0 NOT NULL,
  ATTIVO      SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SERVIZI PRIMARY KEY (ID)
);

CREATE TABLE PRODOTTI (
  ID          INTEGER NOT NULL,
  CODICE      VARCHAR(30),
  DESCRIZIONE VARCHAR(80) NOT NULL,
  PREZZO      NUMERIC(10,2) DEFAULT 0 NOT NULL,
  GIACENZA    INTEGER DEFAULT 0 NOT NULL,
  ATTIVO      SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRODOTTI PRIMARY KEY (ID)
);

CREATE TABLE PAGAMENTI (
  CODICE      VARCHAR(20) NOT NULL,
  DESCRIZIONE VARCHAR(60) NOT NULL,
  CONSTRAINT PK_PAGAMENTI PRIMARY KEY (CODICE)
);

/* ================= AGENDA ================= */

CREATE TABLE APPUNTAMENTI (
  ID            INTEGER NOT NULL,
  INIZIO        TIMESTAMP NOT NULL,
  FINE          TIMESTAMP NOT NULL,
  ID_CLIENTE    INTEGER,
  ID_OPERATORE  INTEGER,
  ID_SERVIZIO   INTEGER,
  STATO         VARCHAR(15) DEFAULT 'PRENOTATO' NOT NULL,
  NOTE          VARCHAR(255),
  CONSTRAINT PK_APPUNTAMENTI PRIMARY KEY (ID),
  CONSTRAINT FK_APP_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTI(ID),
  CONSTRAINT FK_APP_OPERATORE FOREIGN KEY (ID_OPERATORE) REFERENCES OPERATORI(ID),
  CONSTRAINT FK_APP_SERVIZIO FOREIGN KEY (ID_SERVIZIO) REFERENCES SERVIZI(ID),
  CONSTRAINT CK_APP_STATO CHECK (STATO IN ('PRENOTATO','CONFERMATO','ARRIVATO','COMPLETATO','ANNULLATO','NO_SHOW'))
);
CREATE INDEX IDX_APP_INIZIO ON APPUNTAMENTI (INIZIO, ID_OPERATORE);

/* ================= VENDITE ================= */

CREATE TABLE VENDITE (
  ID            INTEGER NOT NULL,
  DATA          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ID_CLIENTE    INTEGER,
  ID_OPERATORE  INTEGER,
  ID_UTENTE     INTEGER,
  IMPONIBILE    NUMERIC(10,2) DEFAULT 0 NOT NULL,
  SCONTO        NUMERIC(10,2) DEFAULT 0 NOT NULL,
  TOTALE        NUMERIC(10,2) DEFAULT 0 NOT NULL,
  PAGAMENTO     VARCHAR(20),
  CHIUSA        SMALLINT DEFAULT 0 NOT NULL,
  NOTE          VARCHAR(255),
  CONSTRAINT PK_VENDITE PRIMARY KEY (ID),
  CONSTRAINT FK_VEN_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTI(ID),
  CONSTRAINT FK_VEN_OPERATORE FOREIGN KEY (ID_OPERATORE) REFERENCES OPERATORI(ID),
  CONSTRAINT FK_VEN_UTENTE FOREIGN KEY (ID_UTENTE) REFERENCES UTENTI(ID),
  CONSTRAINT FK_VEN_PAGAMENTO FOREIGN KEY (PAGAMENTO) REFERENCES PAGAMENTI(CODICE)
);
CREATE INDEX IDX_VENDITE_DATA ON VENDITE (DATA);

CREATE TABLE VENDITE_RIGHE (
  ID            INTEGER NOT NULL,
  ID_VENDITA    INTEGER NOT NULL,
  TIPO          CHAR(1) DEFAULT 'S' NOT NULL,   /* S=servizio P=prodotto */
