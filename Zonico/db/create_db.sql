  ID_PRODOTTO   INTEGER,
  DESCRIZIONE   VARCHAR(80) NOT NULL,
  QUANTITA      INTEGER DEFAULT 1 NOT NULL,
  PREZZO        NUMERIC(10,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_VENDITE_RIGHE PRIMARY KEY (ID),
  CONSTRAINT FK_VR_VENDITA FOREIGN KEY (ID_VENDITA) REFERENCES VENDITE(ID) ON DELETE CASCADE,
  CONSTRAINT FK_VR_SERVIZIO FOREIGN KEY (ID_SERVIZIO) REFERENCES SERVIZI(ID),
  CONSTRAINT FK_VR_PRODOTTO FOREIGN KEY (ID_PRODOTTO) REFERENCES PRODOTTI(ID)
);

