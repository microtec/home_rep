/* ================= UTENTI E PERMESSI ================= */

CREATE TABLE UTENTI (
  ID          INTEGER NOT NULL,
  USERNAME    VARCHAR(30) NOT NULL,
  PASSWORD    VARCHAR(30) NOT NULL,
  NOME        VARCHAR(60),
  ADMIN       SMALLINT DEFAULT 0 NOT NULL,
  ATTIVO      SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_UTENTI PRIMARY KEY (ID),
  CONSTRAINT UQ_UTENTI_USERNAME UNIQUE (USERNAME)
);

CREATE TABLE MODULI (
  CODICE      VARCHAR(20) NOT NULL,
  DESCRIZIONE VARCHAR(60) NOT NULL,
  CONSTRAINT PK_MODULI PRIMARY KEY (CODICE)
);

CREATE TABLE PERMESSI (
  ID_UTENTE   INTEGER NOT NULL,
  MODULO      VARCHAR(20) NOT NULL,
  LETTURA     SMALLINT DEFAULT 1 NOT NULL,
  SCRITTURA   SMALLINT DEFAULT 0 NOT NULL,
  CANCELLA    SMALLINT DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PERMESSI PRIMARY KEY (ID_UTENTE, MODULO),
  CONSTRAINT FK_PERMESSI_UTENTE FOREIGN KEY (ID_UTENTE) REFERENCES UTENTI(ID) ON DELETE CASCADE,
  CONSTRAINT FK_PERMESSI_MODULO FOREIGN KEY (MODULO) REFERENCES MODULI(CODICE)
);

/* ================= ANAGRAFICHE ================= */

CREATE TABLE CLIENTI (
  ID            INTEGER NOT NULL,
  COGNOME       VARCHAR(50) NOT NULL,
  NOME          VARCHAR(50),
  SESSO         CHAR(1),
  DATA_NASCITA  DATE,
  TELEFONO      VARCHAR(20),
  CELLULARE     VARCHAR(20),
  EMAIL         VARCHAR(100),
  INDIRIZZO     VARCHAR(100),
  CAP           VARCHAR(10),
  CITTA         VARCHAR(60),
  PROVINCIA     VARCHAR(2),
  CODICE_FISCALE VARCHAR(16),
  CONSENSO_PRIVACY SMALLINT DEFAULT 0 NOT NULL,
  CONSENSO_MARKETING SMALLINT DEFAULT 0 NOT NULL,
  NOTE          BLOB SUB_TYPE TEXT,
  DATA_INSERIMENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ATTIVO        SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLIENTI PRIMARY KEY (ID)
);
CREATE INDEX IDX_CLIENTI_COGNOME ON CLIENTI (COGNOME, NOME);

CREATE TABLE OPERATORI (
  ID          INTEGER NOT NULL,
  NOME        VARCHAR(60) NOT NULL,
  TELEFONO    VARCHAR(20),
