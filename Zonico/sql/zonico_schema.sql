/* Giacenza aggiornata automaticamente: carico somma, scarico sottrae */
CREATE TRIGGER TRG_MOVIMENTI_AI FOR MOVIMENTI_MAGAZZINO
ACTIVE AFTER INSERT POSITION 0
AS
BEGIN
  IF (NEW.M_TIPO = 'C') THEN
    UPDATE ARTICOLI SET A_GIACENZA = A_GIACENZA + NEW.M_QUANTITA
     WHERE ID = NEW.M_ID_ARTICOLO;
  ELSE
    UPDATE ARTICOLI SET A_GIACENZA = A_GIACENZA - NEW.M_QUANTITA
     WHERE ID = NEW.M_ID_ARTICOLO;
END^

SET TERM ; ^

COMMIT;


