SET TERM ^ ;

CREATE TRIGGER TRG_RUOLI_BI FOR RUOLI
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = GEN_ID(GEN_RUOLI_ID, 1);
END^

